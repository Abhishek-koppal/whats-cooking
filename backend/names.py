def names_in(items: list[str]) -> list[str]:
    """The items made only of such words (so "dal" or "bhindi" never match, but "hello" or "my phone" do)."""
    return [i for i in items if i.split() and all(w.casefold().strip(".'’-") in NAMES for w in i.split())]
